def typ(s):
    """Escape for Typst markup."""
    return s.replace("\\", "\\\\").replace("#", "\\#").replace("$", "\\$") \
            .replace("_", "\\_").replace("[", "\\[").replace("]", "\\]") \
            .replace("@", "\\@")


