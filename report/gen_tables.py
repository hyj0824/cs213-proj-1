def load_summary():
    with open(os.path.join(OUT, "summary.csv"), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def cell(rows, scale, engine, mode, param, warm=True, field="median_ms", fmt="{:.0f}"):
    for r in rows:
        if (r["scale"] == str(scale) and (r["backend"], r["impl"]) == engine
                and r["mode"] == mode and r["param"] == param
                and ("_cold" in r["group"]) != warm
                and "warmup" not in r["group"]):
            return fmt.format(float(r[field]))
    return "--"


def val(rows, scale, engine, mode, param, warm=True, field="median_ms"):
    """Numeric variant of cell(); returns None when the case is absent."""
    for r in rows:
        if (r["scale"] == str(scale) and (r["backend"], r["impl"]) == engine
                and r["mode"] == mode and r["param"] == param
                and ("_cold" in r["group"]) != warm
                and "warmup" not in r["group"]):
            return float(r[field])
    return None


def load_probe_medians():
    path = os.path.join(OUT, "parallel_probe.csv")
    if not os.path.exists(path):
        return {}
    with open(path, newline="", encoding="utf-8") as f:
        pr = list(csv.DictReader(f))
    out = {}
    for g in ("probe_pg0", "probe_pg4", "probe_og1b", "probe_og4b"):
        vals = [int(r["latency_ns"]) / 1e6 for r in pr
                if r["group"] == g and r["ok"] == "1"]
        out[g] = statistics.median(vals) if vals else None
    return out


def load_storage():
    """Parse out/storage_ab.md into one dict per storage target."""
    path = os.path.join(OUT, "storage_ab.md")
    entries = []
    if not os.path.exists(path):
        return entries
    for line in open(path, encoding="utf-8"):
        if not line.startswith("| ") or line.startswith("| target") or set(line) <= set("|- \n"):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) < 12:
            continue
        try:
            entries.append(dict(
                target=c[0], rows=int(c[1]), before=float(c[2]),
                after_update=float(c[3]), growth=float(c[5].rstrip("%")),
                dead=float(c[6]), vacuum=float(c[7]), after_vacuum=float(c[8]),
                full=float(c[9]), after_full=float(c[10]), update=float(c[11])))
        except ValueError:
            continue
    return entries



