#!/usr/bin/env python3
"""Collapse src/bench/*.java into one submission file.

The brief requires the source code to be submitted as a single file named
`[filename].Java` or `[filename].cpp`, uncompressed. The harness is eight Java
files, which is the right structure for the repository and the wrong shape for
the submission form, so this script generates a single-file build that is
byte-for-byte the same code:

  * the package declaration is dropped (so the file works on its own),
  * `public` is stripped from the top-level type declarations (Java allows only
    one public top-level type per file),
  * the entry point class is renamed `Main` -> `DBBench` and made public,
  * imports are merged and deduplicated.

    python3 tools/make_single_file.py     # writes submit/DBBench.java
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "benchmark", "src", "bench")
DST_DIR = os.path.join(ROOT, "submit")
DST = os.path.join(DST_DIR, "DBBench.java")

ORDER = ["Semantics.java", "Backend.java", "Tsv.java", "Stats.java",
         "RawCsv.java", "SqlBackend.java", "FileBackend.java", "Main.java"]

HEADER = '''// ===========================================================================
//  Project 1: DBMS Performance Evaluation -- single-file submission build
//
//  GENERATED by tools/make_single_file.py from benchmark/src/bench/*.java.
//  This file is identical to the multi-file harness except that the package
//  declaration is gone, `public` is dropped from the top-level types (Java
//  permits one public class per file) and the entry point is renamed DBBench.
//
//  Build and run:
//      javac -cp "lib/*" DBBench.java
//      java  -cp ".:lib/*" DBBench --backend pg   --mode scan --keyword the \\
//             --jdbc jdbc:postgresql://127.0.0.1:5432/bench --user bench --pass bench
//      java  -cp ".:lib/*" DBBench --backend og   --mode scan --keyword the \\
//             --jdbc jdbc:postgresql://127.0.0.1:5433/bench --user gaussdb --pass Bench@123
//      java  -cp "."       DBBench --backend file --mode scan --keyword the --data ./data
//
//  The JDBC driver jar is needed only for the two SQL backends; the file backend
//  has no dependencies at all. Put exactly ONE driver on the classpath: the
//  openGauss driver is a pgjdbc fork that ships org.postgresql.Driver as well, so
//  the two jars shadow each other.
//
//  The full harness (scripts, SQL, analysis) lives in the project repository;
//  this file is the same measurement code in submission form.
//
//  Usage:
//      --backend pg|og|file        --mode scan|point|update|counter|join|size
//      --keyword KW  --ids N  --reps N  --warmup N  --scale LABEL
//      --out FILE  --explain DIR   --group LABEL  --run-id ID
//      --jdbc URL --user U --pass P [--parallel N]
//      --data DIR  --file-impl seq|idx|hash  --file-fsync  --allow-corruption
//      --restore-cmd CMD   (runs between destructive repetitions)
//      --pre-rep-cmd CMD   (runs before EVERY repetition; used for cache control)
//      --threads N --iters N        (counter mode)
// ===========================================================================
'''

imports = set()
bodies = []

for name in ORDER:
    path = os.path.join(SRC, name)
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"^package\s+bench;\s*$", "", text, flags=re.M)
    for line in re.findall(r"^import .*;$", text, flags=re.M):
        imports.add(line)
    text = re.sub(r"^import .*;\s*$", "", text, flags=re.M)
    # strip `public` from top-level type declarations only (they start at col 0)
    text = re.sub(r"^(public\s+)((?:final\s+|abstract\s+)?(?:class|interface|enum)\s+\w+)",
                  r"\2", text, flags=re.M)
    if name == "Main.java":
        text = re.sub(r"\bclass Main\b", "class DBBench", text)
        text = re.sub(r"\bMain\.", "DBBench.", text)
    bodies.append(f"// ---------------------------------------------------------------------------\n"
                  f"// from {name}\n"
                  f"// ---------------------------------------------------------------------------\n"
                  + text.strip() + "\n")

os.makedirs(DST_DIR, exist_ok=True)
with open(DST, "w", encoding="utf-8") as f:
    f.write(HEADER)
    f.write("\n")
    for imp in sorted(imports):
        f.write(imp + "\n")
    f.write("\n")
    f.write("\n".join(bodies))

lines = sum(1 for _ in open(DST, encoding="utf-8"))
print(f"wrote {DST} ({lines} lines, {len(imports)} imports, {len(ORDER)} classes)")
